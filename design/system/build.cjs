const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'PARALLAX_DESIGN_BLUEPRINT.md'),'utf8');
const matches=[...source.matchAll(/^### (C\d{2}) (.+)\r?\n([\s\S]*?)(?=^### C\d{2}|^## |$(?![\s\S]))/gm)];
const sections=['Variants','Required anatomy','Behaviour','Constraints','Acceptance'];
const components=matches.map(m=>{const o={id:m[1],name:m[2].trim()};for(const s of sections){const escaped=s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');const v=m[3].match(new RegExp('#### '+escaped+'\\r?\\n([\\s\\S]*?)(?=#### |$)'));o[s.toLowerCase().replace(' ','_')]=v?[...v[1].matchAll(/^- (.+)/gm)].map(x=>x[1].trim()):[];}return o;});
if(components.length!==40)throw Error('Expected 40 blueprint components, got '+components.length);
const tokens=JSON.parse(fs.readFileSync(path.join(__dirname,'token-source.json'),'utf8'));
fs.writeFileSync(path.join(__dirname,'tokens.json'),JSON.stringify(tokens,null,2)+'\n');
fs.writeFileSync(path.join(__dirname,'components.json'),JSON.stringify(components,null,2)+'\n');
let css='/* Generated by build.cjs from token-source.json. */\n:root{\n';
for(const [k,v]of Object.entries(tokens.primitives))css+=` --primitive-${k}:${v};\n`;
for(const [k,v]of Object.entries(tokens.semantic))css+=` --${k.replace(/[A-Z]/g,m=>'-'+m.toLowerCase())}:var(--primitive-${v});\n`;
for(const [k,v]of Object.entries(tokens.spacing))css+=` --space-${k}:${v}px;\n`;
for(const [k,v]of Object.entries(tokens.radius))css+=` --radius-${k}:${v}px;\n`;
for(const [k,v]of Object.entries(tokens.motion))css+=` --motion-${k}:${v}ms;\n`;
for(const [k,v]of Object.entries(tokens.typography))css+=` --font-${k}:'${v.family}',${v.fallback};\n`;
css+='}\n';fs.writeFileSync(path.join(__dirname,'tokens.css'),css);
console.log('Built Atlas+ tokens and '+components.length+' blueprint component contracts.');
